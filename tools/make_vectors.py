#!/usr/bin/env python3
"""
Export golden test vectors for the C pitch module (tests/vectors/).

The C pitch module will be checked stage by stage against these files, so a failing test
points at one stage (decimator, difference function, CMNDF, final result) instead of
"the pitch is wrong". Everything is computed by tools/pitch_ref.py in float32, the
precision the Cortex-M4F uses.

Usage:
    python tools/make_vectors.py

Files in tests/vectors/ (all little-endian, no headers; sizes and config in vectors.txt):
    vectors.txt                 config, file list, sizes, tolerances (key = value, # comments)
    fir_taps.f32                anti-alias FIR coefficients, the same values as fir_taps.h
    <case>_input.i16            int16 input at 32 kHz, a whole number of 256-sample blocks
    <case>_decimated.f32        decimator output at 8 kHz (input scaled by 1/32768 first)
    <case>_d.f32                difference function d[tau], tau = 0 .. tau_max+1, for the
                                frames listed in vectors.txt (one row per frame)
    <case>_dprime.f32           CMNDF d'[tau] for the same frames
    <case>_results.csv          one row per hop: frame, time_s, tau, freq_hz, confidence, valid
                                (tau = YIN period at 8 kHz before the 32 kHz refinement;
                                 freq_hz = after refinement; time_s = newest input sample)

Also writes lib/pitch/src/fir_taps.h, the FIR taps as a C array for the firmware and the
host tests. It is generated: never edit it by hand. It lives in the module, not here, so the
firmware never includes anything from tests/.

Regenerate whenever pitch_ref.Config or the FIR changes: vectors.txt records the config
that produced them.
"""
import csv
import sys
from datetime import date
from pathlib import Path

import numpy as np
from scipy.io import wavfile

sys.path.insert(0, str(Path(__file__).resolve().parent))
import pitch_ref as pr                       # noqa: E402

REPO_ROOT = Path(__file__).resolve().parent.parent
OUT = REPO_ROOT / "tests" / "vectors"
FIR_HEADER = REPO_ROOT / "lib" / "pitch" / "src" / "fir_taps.h"

CASES = [  # (case name, source file, what it exercises)
    ("tone440", "data/captures/20261025_132155_440.wav", "pure tone, absolute accuracy"),
    ("e2_open", "data/captures/20261025_140314_E2_open_amp.wav", "guitar low E, rich harmonics"),
    ("e2_fret12", "data/captures/20261025_140923_E2_fret12pluck_amp.wav", "no even harmonics"),
    ("e3_harmonic", "data/captures/20261025_140937_E3_harm12_amp.wav", "natural harmonic"),
    ("e6_fret24", "data/captures/20261025_141033_E6_amp.wav", "top of the range, period ~6 samples"),
    ("e1_bass", "data/captures/20261025_194529_E1_bass_amp.wav", "bass low E, weak fundamental"),
    ("b0_bass", "data/captures/20261025_194623_B0_bass_amp.wav", "lowest note, near tau_max"),
    ("e1_missing", "data/synthetic/20261025_000000_syn_E1_missing_fund.wav", "no fundamental at all"),
    ("silence", "data/captures/20261025_130307_silence.wav", "no note: every result invalid"),
]

TOLERANCES = {
    "decimated_abs": 1e-6,       # |C - ref|, signal scaled to +-1 (float32 sums in a different order)
    "d_rel": 1e-4,               # |C - ref| / max(d) per frame
    "dprime_abs": 1e-4,
    "tau_abs": 1e-3,             # detector samples
    "freq_cents": 0.01,
    "confidence_abs": 1e-4,      # valid flags may differ only when confidence is this close to the gate
}


def write_header(path, taps, cfg):
    lines = [
        "/* GENERATED by tools/make_vectors.py from tools/pitch_ref.py -- do not edit. */",
        "/* Anti-alias FIR for 32 kHz -> 8 kHz decimation: Kaiser window method,",
        f"   passband {cfg.fir_pass_hz:g} Hz, stopband {cfg.fir_stop_hz:g} Hz, {cfg.fir_atten_db:g} dB,"
        f" {len(taps)} taps, symmetric (linear phase), delay {(len(taps) - 1) // 2} samples. */",
        "#ifndef FIR_TAPS_H",
        "#define FIR_TAPS_H",
        "",
        f"#define FIR_NUM_TAPS {len(taps)}",
        "",
        "static const float fir_taps[FIR_NUM_TAPS] = {",
    ]
    for i in range(0, len(taps), 4):
        lines.append("    " + " ".join(f"{float(v): .9e}f," for v in taps[i:i + 4]))
    lines += ["};", "", "#endif /* FIR_TAPS_H */", ""]
    path.write_text("\n".join(lines), encoding="ascii")


def main():
    cfg = pr.replace(pr.Config(), dtype=np.float32)
    OUT.mkdir(parents=True, exist_ok=True)
    taps = pr.fir_taps(cfg).astype(np.float32)
    taps.tofile(OUT / "fir_taps.f32")
    FIR_HEADER.parent.mkdir(parents=True, exist_ok=True)
    write_header(FIR_HEADER, taps, cfg)

    meta = [
        "# Golden vectors for the C pitch module. Generated by tools/make_vectors.py",
        f"# on {date.today().isoformat()}. All binary files little-endian, no headers.",
        "",
        "[config]",
        f"fs_in = {cfg.fs_in}", f"decim = {cfg.decim}", f"fs = {cfg.fs}",
        f"block = {pr.BLOCK}", f"window = {cfg.window}", f"hop = {cfg.hop}",
        f"f_min = {cfg.f_min:g}", f"f_max = {cfg.f_max:g}",
        f"tau_min = {cfg.tau_min}", f"tau_max = {cfg.tau_max}",
        f"integration_window_W = {cfg.window - cfg.tau_max - 1}",
        f"function_length = {cfg.tau_max + 2}",
        f"method = {cfg.method}", f"yin_threshold = {cfg.yin_threshold:g}",
        f"interp = {cfg.interp}", f"refine = {int(cfg.refine)}",
        f"refine_search = {cfg.decim}", f"refine_max_lag = {cfg.tau_max * cfg.decim + cfg.decim + 2}",
        f"gate = {cfg.gate:g}", "precision = float32",
        f"fir_num_taps = {len(taps)}", f"fir_pass_hz = {cfg.fir_pass_hz:g}",
        f"fir_stop_hz = {cfg.fir_stop_hz:g}", f"fir_atten_db = {cfg.fir_atten_db:g}",
        "",
        "[tolerances]",
    ] + [f"{k} = {v:g}" for k, v in TOLERANCES.items()] + ["", "[cases]",
         "# name = input samples, decimated samples, results rows, frames with d/d' saved | source | purpose",
         "# results.csv: tau = YIN period at 8 kHz before refinement, freq_hz = after the 32 kHz refinement"]

    for name, src, purpose in CASES:
        _, data = wavfile.read(REPO_ROOT / src)
        data = data[: len(data) - len(data) % pr.BLOCK].astype(np.int16)
        data.tofile(OUT / f"{name}_input.i16")

        dec = pr.Decimator(pr.fir_taps(cfg), cfg.decim, np.float32)
        x = data.astype(np.float32) / np.float32(pr.FULL_SCALE)
        decimated = np.concatenate([dec.process(x[i:i + pr.BLOCK]) for i in range(0, len(x), pr.BLOCK)])
        decimated.astype(np.float32).tofile(OUT / f"{name}_decimated.f32")

        tracker = pr.PitchTracker(cfg)
        rows, windows = [], []
        for i in range(0, len(data), pr.BLOCK):
            for r in tracker.push(data[i:i + pr.BLOCK]):
                rows.append(r)
                windows.append(tracker.win.copy())
        keep = sorted({0, len(rows) // 2, len(rows) - 1})
        d_rows, dp_rows = [], []
        for k in keep:
            _, f = pr.yin(windows[k], cfg, return_functions=True)
            d_rows.append(f["d"])
            dp_rows.append(f["dprime"])
        np.asarray(d_rows, dtype=np.float32).tofile(OUT / f"{name}_d.f32")
        np.asarray(dp_rows, dtype=np.float32).tofile(OUT / f"{name}_dprime.f32")
        with (OUT / f"{name}_results.csv").open("w", newline="", encoding="ascii") as f:
            w = csv.writer(f)
            w.writerow(["frame", "time_s", "tau", "freq_hz", "confidence", "valid"])
            for i, r in enumerate(rows):
                w.writerow([i, f"{r.time_s:.6f}", f"{r.tau:.6f}", f"{r.freq_hz:.6f}",
                            f"{r.confidence:.7f}", int(r.valid)])
        meta.append(f"{name} = {len(data)}, {len(decimated)}, {len(rows)}, frames {' '.join(map(str, keep))}"
                    f" | {src} | {purpose}")
        valid = [r for r in rows if r.valid]
        med = np.median([r.freq_hz for r in valid]) if valid else float("nan")
        print(f"  {name:12} {len(rows):3} results, {len(valid):3} valid, median {med:9.3f} Hz   ({purpose})")

    (OUT / "vectors.txt").write_text("\n".join(meta) + "\n", encoding="ascii")
    total = sum(p.stat().st_size for p in OUT.iterdir())
    print(f"wrote {len(list(OUT.iterdir()))} files, {total / 1024:.0f} KB, to {OUT.relative_to(REPO_ROOT)}")
    print(f"wrote {FIR_HEADER.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
